const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync(__dirname+'/../dist/bridge.js','utf8');
const start=source.indexOf('const WAITING_CASE=');
const end=source.indexOf('function statisticsPointer',start);
assert(start>=0&&end>start,'waiting-detail helpers are present');
const context={Date,Error,Number,Array,String,Math};
vm.createContext(context);
vm.runInContext(source.slice(start,end).replaceAll('export function','function'),context);
const now=Date.parse('2026-10-23T14:30:00Z');
const valid=[{case_id:'case-59808652bdb90ad9f14eddb3',name:' Dasha ',reason:' Chýba deň a mesiac narodenín. ',waiting_since:'2026-10-23T13:56:33Z'}];
const rows=context.validateWaitingDetails(valid);
assert.equal(rows.length,1);assert.equal(rows[0].name,'Dasha');assert.equal(rows[0].reason,'Chýba deň a mesiac narodenín.');
assert.equal(context.validateWaitingDetails(undefined),null);
assert.equal(context.waitingDuration('2026-10-23T14:29:50Z',now),'práve teraz');
assert.equal(context.waitingDuration('2026-10-23T13:25:00Z',now),'1 h 5 min');
assert.equal(context.waitingDuration('2026-10-21T11:30:00Z',now),'2 d 3 h');
for(const invalid of [null,{},new Array(101).fill(valid[0]),[{...valid[0],case_id:'../../secret'}],[{...valid[0],name:''}],[{...valid[0],reason:''}],[{...valid[0],waiting_since:'not-a-date'}]])assert.throws(()=>context.validateWaitingDetails(invalid));
const html=fs.readFileSync(__dirname+'/../dist/index.html','utf8');
assert(html.indexOf('id="tinder-waiting"')>html.indexOf('id="statistics-panel"'),'waiting section follows statistics');
assert(source.includes('validateWaitingDetails(p.awaiting_details)'),'client consumes the backend waiting-detail contract');
assert(!source.includes('validateWaitingDetails(p.waiting_details)'),'legacy mismatched field cannot silently return');
assert(source.includes('setInterval(refreshWaitingDurations,30000)'),'elapsed times refresh without waiting for the network');
assert(!source.includes('localStorage.setItem')||!source.slice(start,end).includes('localStorage'),'waiting detail helpers never persist private values');
console.log('Waiting chats: strict private-payload validation, durations, placement and no persistence passed.');
